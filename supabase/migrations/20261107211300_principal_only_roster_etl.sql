begin;

create table if not exists public.etl_runs (
  id bigint generated by default as identity primary key,
  batch_id uuid not null unique default gen_random_uuid(),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  status text not null default 'started'
    check (status in ('started', 'completed', 'completed_with_errors', 'failed')),
  source_file text,
  students_inserted integer not null default 0 check (students_inserted >= 0),
  staff_inserted integer not null default 0 check (staff_inserted >= 0),
  rejected_count integer not null default 0 check (rejected_count >= 0),
  details jsonb not null default '{}'::jsonb,
  check (ended_at is null or ended_at >= started_at)
);

create table if not exists public.etl_rejected_records (
  id bigint generated by default as identity primary key,
  batch_id uuid not null
    references public.etl_runs (batch_id) on delete cascade,
  sheet text not null,
  row_number integer check (row_number > 0),
  identifier text,
  reason text not null,
  row_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists etl_rejected_records_batch_id_idx
  on public.etl_rejected_records (batch_id);

alter table public.etl_runs enable row level security;
alter table public.etl_rejected_records enable row level security;
revoke all on table public.etl_runs, public.etl_rejected_records from public, anon, authenticated;
grant select on table public.etl_runs, public.etl_rejected_records to authenticated;

drop policy if exists etl_runs_select_roster_admin on public.etl_runs;
create policy etl_runs_select_roster_admin
  on public.etl_runs for select to authenticated
  using (private.has_roster_admin_role());

drop policy if exists etl_rejected_records_select_roster_admin
  on public.etl_rejected_records;
create policy etl_rejected_records_select_roster_admin
  on public.etl_rejected_records for select to authenticated
  using (private.has_roster_admin_role());

create or replace function private.require_principal_roster_etl_import()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $function$
declare
  v_actor_user_id uuid;
begin
  if coalesce(new.details ->> 'uploaded_by', '') !~*
    '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    raise exception 'ETL imports must identify an active Principal account.';
  end if;

  v_actor_user_id := (new.details ->> 'uploaded_by')::uuid;
  if not exists (
    select 1
    from public.users as profile
    where profile.id = v_actor_user_id
      and profile.is_active
      and profile.role = 'principal'
  ) then
    raise exception 'Only an active Principal account can import roster data.';
  end if;

  return new;
end
$function$;

revoke all on function private.require_principal_roster_etl_import()
  from public, anon, authenticated;

drop trigger if exists etl_runs_require_principal_importer on public.etl_runs;
create trigger etl_runs_require_principal_importer
  before insert on public.etl_runs
  for each row
  execute function private.require_principal_roster_etl_import();

commit;
